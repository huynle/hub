// The hub's web/ files behind one interface: read from disk (a checkout, the npm package, the Docker
// image) or from files embedded in a compiled binary (`bun build --compile`, see scripts/gen-web-entry.ts).
import { existsSync, readFileSync, statSync } from "node:fs"
import path from "node:path"

export interface WebAssets {
  /** The bytes of web/<name> ("app.js", "sub/x.js"), or undefined when there is no such file. */
  read(name: string): Uint8Array<ArrayBuffer> | undefined
}

/** Files under `dir`; anything resolving outside it (or a folder) is not found. */
export function diskAssets(dir: string): WebAssets {
  const root = path.resolve(dir)
  return {
    read(name) {
      if (!name) return undefined
      const file = path.resolve(root, name)
      if (!file.startsWith(root + path.sep) || !existsSync(file) || !statSync(file).isFile()) return undefined
      return readFileSync(file)
    },
  }
}

/**
 * A name → path map, as `import f from "../web/app.js" with { type: "file" }` gives it: a path inside the
 * compiled binary ($bunfs), or the file on disk when the entry runs from source.
 */
export function embeddedAssets(files: Readonly<Record<string, string>>): WebAssets {
  const table = new Map(Object.entries(files))
  return {
    read(name) {
      const file = table.get(name)
      if (!file) return undefined
      try {
        return readFileSync(file)
      } catch {
        return undefined
      }
    },
  }
}

/** Files that belong in the page (not type declarations, not hidden files). */
export function isWebAsset(name: string): boolean {
  return !name.startsWith(".") && !name.endsWith(".d.ts")
}

/** Source of a module that embeds web/ files: `export default { "<name>": <embedded path>, … }`. */
export function webAssetModule(names: readonly string[], from: string): string {
  const files = names.filter(isWebAsset)
  const imports = files.map((name, i) => `import f${i} from ${JSON.stringify(`${from}/${name}`)} with { type: "file" }`)
  const entries = files.map((name, i) => `  ${JSON.stringify(name)}: f${i},`)
  return [
    "// Generated by scripts/gen-web-entry.ts: web/ files embedded in the compiled hub. Do not edit.",
    ...imports,
    "",
    "export default {",
    ...entries,
    "} as Record<string, string>",
    "",
  ].join("\n")
}
